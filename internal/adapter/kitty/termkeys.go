// kitty's half of the terminal keys: revier.conf, the file revier owns whole,
// and the one include of it at the top of kitty.conf. Which keys go in, and
// what a map in kitty.conf means for them, is the core's.
//
// kitty.conf is often a file in a dotfiles repository, and the kitty
// directory a link into it (GNU stow folds a directory that way). Every write
// goes through the links to the file they point at, keeps its mode, and
// never replaces a link: fsutil.WriteThrough.

const (
	revierConf = "revier.conf"
	kittyConf  = "kitty.conf"

	termHeader     = "# Generated by revier from config.toml: revier term install rewrites this file. Do not edit it."
	includeMarker  = "# revier term install: revier's keys; your own maps below win"
	includeRevier  = "include " + revierConf
	launchPrefix   = "launch --type=background --copy-env sh -c "
	launchSuffix   = " sh @active-kitty-window-id"
	scriptPanel    = ` --panel "$1"`
	scriptFallback = " || kitten @ launch --type=tab --cwd=current"
)

// ConfigDir is kitty's configuration directory, found as kitty finds it:
// KITTY_CONFIG_DIRECTORY when it is set, else $XDG_CONFIG_HOME/kitty when that
// holds a kitty.conf, else ~/.config/kitty.
func ConfigDir() (string, error) {
	if dir := os.Getenv("KITTY_CONFIG_DIRECTORY"); dir != "" {
		return dir, nil
	}
	if xdg := os.Getenv("XDG_CONFIG_HOME"); xdg != "" {
		dir := filepath.Join(xdg, "kitty")
		if _, err := os.Stat(filepath.Join(dir, kittyConf)); err == nil {
			return dir, nil
		}
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, ".config", "kitty"), nil
}

// TermKeys reads the keys kitty holds for revier. It writes nothing:
// TermKeyWriter does.
type TermKeys struct{}

func (TermKeys) Name() string { return "kitty" }

func (TermKeys) Read(context.Context) (revier.TermKeyState, error) {
	dir, err := ConfigDir()
	if err != nil {
		return revier.TermKeyState{}, err
	}
	state := revier.TermKeyState{
		File:   filepath.Join(dir, revierConf),
		Config: filepath.Join(dir, kittyConf),
	}
	if state.FileDangling, err = fsutil.DanglingLink(state.File); err != nil {
		return state, err
	}
	if state.ConfigDangling, err = fsutil.DanglingLink(state.Config); err != nil {
		return state, err
	}
	own, err := readFile(state.File)
	if err != nil {
		return state, err
	}
	state.FileExists = own != nil
	state.Bindings = parseBindings(string(own))

	main, err := readFile(state.Config)
	if err != nil {
		return state, err
	}
	state.ConfigExists = main != nil
	state.Include, state.IncludeOwned = findInclude(lines(string(main)), dir)
	state.Maps = parseMaps(lines(string(main)))
	return state, nil
}

// TermKeyWriter is TermKeys that also writes revier.conf and the include.
type TermKeyWriter struct{ TermKeys }

// Write makes revier.conf hold the bindings, and puts the include at the top
// of kitty.conf when no line includes revier.conf yet: at the top, so a map
// the user writes below it, such as one for windows that run tmux, keeps the
// last word. A file that already holds what would be written is not written.
// kitty reloads a changed kitty.conf by itself.
func (TermKeyWriter) Write(_ context.Context, bindings []revier.TermBinding) error {
	dir, err := checkedConfigDir()
	if err != nil {
		return err
	}
	file := filepath.Join(dir, revierConf)
	data := renderBindings(bindings)
	old, err := readFile(file)
	if err != nil {
		return err
	}
	if old == nil || string(old) != data {
		if err := writeThrough(file, data); err != nil {
			return err
		}
	}

	conf := filepath.Join(dir, kittyConf)
	main, err := readFile(conf)
	if err != nil {
		return err
	}
	if at, _ := findInclude(lines(string(main)), dir); at > 0 {
		return nil
	}
	return writeThrough(conf, includeMarker+"\n"+includeRevier+"\n"+string(main))
}

// Remove deletes revier.conf, through a link to the file it points at, and
// the include revier wrote, and kitty.conf when nothing else is in it: an
// install that created it leaves no empty file behind. An include the user
// wrote stays.
func (TermKeyWriter) Remove(context.Context) error {
	dir, err := checkedConfigDir()
	if err != nil {
		return err
	}
	file := filepath.Join(dir, revierConf)
	if _, err := os.Lstat(file); err == nil {
		real, err := fsutil.Resolve(file)
		if err != nil {
			return err
		}
		if err := os.Remove(real); err != nil {
			return err
		}
		slog.Info("kitty keys removed", "path", real)
	} else if !errors.Is(err, fs.ErrNotExist) {
		return err
	}

	conf := filepath.Join(dir, kittyConf)
	main, err := readFile(conf)
	if err != nil || main == nil {
		return err
	}
	all := lines(string(main))
	at, owned := findInclude(all, dir)
	if !owned {
		return nil
	}
	// The include is line at; revier's marker is the line above it.
	kept := strings.Join(append(all[:at-2:at-2], all[at:]...), "")
	// A kitty.conf that is itself a link stays, emptied: removing the file
	// it points at would leave the link pointing at nothing.
	if info, err := os.Lstat(conf); err != nil {
		return err
	} else if kept != "" || info.Mode()&os.ModeSymlink != 0 {
		return writeThrough(conf, kept)
	}
	real, err := fsutil.Resolve(conf)
	if err != nil {
		return err
	}
	if err := os.Remove(real); err != nil {
		return err
	}
	slog.Info("kitty config removed", "path", real)
	return nil
}

// checkedConfigDir is ConfigDir, once neither revier.conf nor kitty.conf
// is behind a link to nothing: the check runs before the first write, so a
// refused run writes neither file.
func checkedConfigDir() (string, error) {
	dir, err := ConfigDir()
	if err != nil {
		return "", err
	}
	for _, name := range []string{revierConf, kittyConf} {
		if err := fsutil.RefuseDangling(filepath.Join(dir, name)); err != nil {
			return "", err
		}
	}
	return dir, nil
}

// readFile is the file's content through links, nil when it is not there.
func readFile(path string) ([]byte, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	return data, err
}

func writeThrough(path, data string) error {
	real, err := fsutil.WriteThrough(path, []byte(data))
	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	slog.Info("kitty config written", "path", real)
	return nil
}

// lines splits text into its lines, each with its newline; the last one has
// none when the file does not end in one.
func lines(text string) []string {
	out := strings.SplitAfter(text, "\n")
	if out[len(out)-1] == "" {
		out = out[:len(out)-1]
	}
	return out
}

// renderBindings is revier.conf: the header, then one map per binding.
func renderBindings(bindings []revier.TermBinding) string {
	var b strings.Builder
	b.WriteString(termHeader + "\n")
	for _, tb := range bindings {
		b.WriteString(renderBinding(tb) + "\n")
	}
	return b.String()
}

// renderBinding is the map of one binding. kitty starts sh out of sight, with
// the id of the focused window, and in kitty's own directory: one taken from
// the window, --cwd=current, fails to start sh at all once that directory is
// removed. revier opens the tab beside the window, and reads the window's
// directory itself (decisions.md D153). When revier fails - it is not on the
// PATH, or its configuration does not load - the fallback opens kitty's own
// tab, so the key still gives a terminal. No --allow-remote-control: a launched
// process that has it is answered by the kitty it runs in, and that kitty
// cannot find the window revier is asked about.
func renderBinding(tb revier.TermBinding) string {
	words := make([]string, len(tb.Args))
	for i, a := range tb.Args {
		words[i] = shellQuote(a)
	}
	script := "revier " + strings.Join(words, " ") + scriptPanel + scriptFallback
	return "map " + kittyChord(tb.Chord) + " " + launchPrefix + shellQuote(script) + launchSuffix
}

// plainWord is a word sh and kitty both read as itself.
var plainWord = regexp.MustCompile(`^[A-Za-z0-9._/@%+=:,-]+$`)

// shellQuote is s as one word for sh, and for kitty, which splits a map's
// arguments by the same rules.
func shellQuote(s string) string {
	if plainWord.MatchString(s) {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// parseBindings reads revier.conf back. A map that is not one revier writes
// is a binding with no arguments, so the file reads as one install rewrites.
func parseBindings(text string) []revier.TermBinding {
	var out []revier.TermBinding
	for _, line := range lines(text) {
		words, err := splitWords(strings.TrimSpace(line))
		if err != nil || len(words) < 3 || words[0] != "map" {
			continue
		}
		out = append(out, revier.TermBinding{Chord: readChord(words[1], defaultKittyMod), Args: revierArgs(words[2:])})
	}
	return out
}

// revierArgs is revier's argv in the launch revier writes, or nil when words
// are not that launch.
func revierArgs(words []string) []string {
	want, _ := splitWords(launchPrefix + "x" + launchSuffix)
	if len(words) != len(want) {
		return nil
	}
	for i, w := range want {
		if w != "x" && words[i] != w {
			return nil
		}
	}
	script := words[len(want)-3]
	rest, ok := strings.CutSuffix(script, scriptPanel+scriptFallback)
	if !ok {
		return nil
	}
	args, err := splitWords(rest)
	if err != nil || len(args) < 2 || args[0] != "revier" {
		return nil
	}
	return args[1:]
}

// splitWords splits a line as sh does, and kitty with it: blanks separate,
// single quotes keep everything, double quotes keep all but a backslash
// before $, `, " and \, and a backslash outside quotes keeps the next byte.
func splitWords(s string) ([]string, error) {
	var out []string
	var word strings.Builder
	in := false
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == ' ' || c == '\t':
			if in {
				out = append(out, word.String())
				word.Reset()
				in = false
			}
			continue
		case c == '\'':
			end := strings.IndexByte(s[i+1:], '\'')
			if end < 0 {
				return nil, fmt.Errorf("unclosed quote")
			}
			word.WriteString(s[i+1 : i+1+end])
			i += end + 1
		case c == '"':
			i++
			for ; i < len(s) && s[i] != '"'; i++ {
				if s[i] == '\\' && i+1 < len(s) && strings.IndexByte("$`\"\\", s[i+1]) >= 0 {
					i++
				}
				word.WriteByte(s[i])
			}
			if i >= len(s) {
				return nil, fmt.Errorf("unclosed quote")
			}
		case c == '\\' && i+1 < len(s):
			i++
			word.WriteByte(s[i])
		default:
			word.WriteByte(c)
		}
		in = true
	}
	if in {
		out = append(out, word.String())
	}
	return out, nil
}

// findInclude is the line, from 1, of the first include of revier.conf in
// kitty.conf, and whether it is revier's: the include line right below
// revier's marker. A user's include or globinclude that names revier.conf
// counts the same, so install adds no second one.
func findInclude(all []string, dir string) (int, bool) {
	want := filepath.Join(dir, revierConf)
	for i, line := range all {
		key, value := directive(line)
		var names bool
		switch key {
		case "include":
			names = configPath(dir, value) == want
		case "globinclude":
			names, _ = filepath.Match(configPath(dir, value), want)
		}
		if names {
			owned := i > 0 && strings.TrimSpace(all[i-1]) == includeMarker && strings.TrimSpace(line) == includeRevier
			return i + 1, owned
		}
	}
	return 0, false
}

// directive is a kitty.conf line's option name and its value.
func directive(line string) (key, value string) {
	line = strings.TrimSpace(line)
	if line == "" || strings.HasPrefix(line, "#") {
		return "", ""
	}
	at := strings.IndexAny(line, " \t")
	if at < 0 {
		return line, ""
	}
	return line[:at], strings.TrimSpace(line[at+1:])
}

// configPath is a path kitty.conf names, as kitty reads it: ~ is the home
// directory, and a relative path is relative to the configuration directory.
func configPath(dir, p string) string {
	if rest, ok := strings.CutPrefix(p, "~/"); ok {
		if home, err := os.UserHomeDir(); err == nil {
			p = filepath.Join(home, rest)
		}
	}
	if !filepath.IsAbs(p) {
		p = filepath.Join(dir, p)
	}
	return filepath.Clean(p)
}

// defaultKittyMod is what kitty_mod stands for when kitty.conf does not set it.
const defaultKittyMod = "ctrl+shift"

// parseMaps is every map of one key in kitty.conf, in file order. A map of a
// key sequence, or of a keyboard mode other than the default, holds no key a
// press reaches first, and is left out.
func parseMaps(all []string) []revier.TermMap {
	mod := defaultKittyMod
	for _, line := range all {
		if key, value := directive(line); key == "kitty_mod" && value != "" {
			mod = value
		}
	}
	var out []revier.TermMap
	for i, line := range all {
		if key, _ := directive(line); key != "map" {
			continue
		}
		words, err := splitWords(strings.TrimSpace(line))
		if err != nil {
			continue
		}
		m, ok := parseMap(words[1:], mod)
		if !ok {
			continue
		}
		m.Line = i + 1
		out = append(out, m)
	}
	return out
}

// parseMap reads the words after "map": the options, then the key.
func parseMap(words []string, mod string) (revier.TermMap, bool) {
	var m revier.TermMap
	for len(words) > 0 && strings.HasPrefix(words[0], "--") {
		name, value, ok := strings.Cut(words[0], "=")
		words = words[1:]
		if !ok && len(words) > 0 {
			value, words = words[0], words[1:]
		}
		switch name {
		case "--when-focus-on":
			m.Condition = "when " + value
		case "--mode":
			return m, false
		}
	}
	if len(words) == 0 || strings.Contains(words[0], ">") {
		return m, false
	}
	m.Chord = readChord(words[0], mod)
	return m, true
}

// kittyKey is how kitty names the canonical keys whose name it does not
// share: kitty reads "pgdown" and most punctuation as no key.
var kittyKey = map[string]string{
	"esc": "escape", "pgup": "page_up", "pgdown": "page_down",
	",": "comma", ".": "period", "/": "slash", `\`: "backslash", ";": "semicolon",
	":": "colon", "'": "apostrophe", "`": "grave", "~": "tilde", "=": "equal",
	"_": "underscore", "|": "bar", "*": "star", "[": "left_bracket", "]": "right_bracket",
}

// kittyKeyAlias is every kitty key name the core's chord parser does not
// read, in the spelling it reads. kitty's own aliases go here too.
var kittyKeyAlias = map[string]string{
	"pgdn": "page_down", "arrowup": "up", "arrowdown": "down", "arrowleft": "left",
	"arrowright": "right", "del": "delete", "left_bracket": "[", "right_bracket": "]",
	"tilde": "~", "dot": ".", "hyphen": "minus", "star": "*", "multiply": "*",
	"pipe": "|", "spc": "space", "grave_accent": "`",
}

// kittyModAlias is every kitty modifier name the core's chord parser does
// not read.
var kittyModAlias = map[string]string{
	"opt": "alt", "option": "alt", "cmd": "super", "command": "super",
}

// kittyChord is a canonical chord in kitty's key names.
func kittyChord(chord string) string {
	parts := strings.Split(chord, "+")
	if k, ok := kittyKey[parts[len(parts)-1]]; ok {
		parts[len(parts)-1] = k
	}
	return strings.Join(parts, "+")
}

// readChord is a kitty key in a spelling the core's chord parser reads:
// kitty_mod stands for mod, and kitty's own names are put back.
func readChord(key, mod string) string {
	parts := strings.Split(strings.ToLower(key), "+")
	var out []string
	for i, p := range parts {
		if i == len(parts)-1 {
			if a, ok := kittyKeyAlias[p]; ok {
				p = a
			}
			out = append(out, p)
			continue
		}
		switch {
		case p == "kitty_mod":
			out = append(out, strings.Split(strings.ToLower(mod), "+")...)
		case kittyModAlias[p] != "":
			out = append(out, kittyModAlias[p])
		default:
			out = append(out, p)
		}
	}
	return strings.Join(out, "+")
}
