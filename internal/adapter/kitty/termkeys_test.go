const marker = "# revier term install: revier's keys; your own maps below win\ninclude revier.conf\n"

var bindings = []revier.TermBinding{
	{Chord: "ctrl+shift+t", Args: []string{"shell", "new"}},
	{Chord: "ctrl+shift+z", Args: []string{"agent", "new"}},
	{Chord: "ctrl+shift+d", Args: []string{"agent", "new", "dtop"}},
}

// kittyDir points KITTY_CONFIG_DIRECTORY at dir, a fresh directory.
func kittyDir(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	t.Setenv("KITTY_CONFIG_DIRECTORY", dir)
	return dir
}

func write(t *testing.T, path, text string, mode os.FileMode) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(text), mode); err != nil {
		t.Fatal(err)
	}
}

func link(t *testing.T, target, path string) {
	t.Helper()
	if err := os.Symlink(target, path); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func install(t *testing.T) {
	t.Helper()
	if err := (kitty.TermKeyWriter{}).Write(context.Background(), bindings); err != nil {
		t.Fatalf("Write: %v", err)
	}
}

func uninstall(t *testing.T) {
	t.Helper()
	if err := (kitty.TermKeyWriter{}).Remove(context.Background()); err != nil {
		t.Fatalf("Remove: %v", err)
	}
}

func state(t *testing.T) revier.TermKeyState {
	t.Helper()
	s, err := (kitty.TermKeys{}).Read(context.Background())
	if err != nil {
		t.Fatalf("Read: %v", err)
	}
	return s
}

func isLink(t *testing.T, path string) bool {
	t.Helper()
	info, err := os.Lstat(path)
	if err != nil {
		t.Fatal(err)
	}
	return info.Mode()&os.ModeSymlink != 0
}

// The line the spec gives for the default agent's key, word for word.
func TestTheDefaultAgentsMapIsTheDocumentedLine(t *testing.T) {
	dir := kittyDir(t)
	install(t)
	want := `map ctrl+shift+z launch --type=background --copy-env --cwd=current sh -c 'revier agent new --panel "$1" --dir . || kitten @ launch --type=tab --cwd=current' sh @active-kitty-window-id`
	got := strings.Split(read(t, filepath.Join(dir, "revier.conf")), "\n")
	if got[0] != "# Generated by revier from config.toml: revier term install rewrites this file. Do not edit it." {
		t.Errorf("header = %q", got[0])
	}
	if got[2] != want {
		t.Errorf("agent line =\n%s\nwant\n%s", got[2], want)
	}
	if !strings.Contains(got[3], "'revier agent new dtop --panel") {
		t.Errorf("named agent line = %q, want the name before the flags", got[3])
	}
	if strings.Contains(read(t, filepath.Join(dir, "revier.conf")), os.Getenv("HOME")) {
		t.Error("revier.conf names the home directory")
	}
}

// The script is one word to kitty and, split again by sh, runs revier with
// exactly the arguments given: a name with a quote, a blank and a dollar sign
// stays one argument and expands nothing.
func TestTheGeneratedScriptQuotesEveryArgument(t *testing.T) {
	dir := kittyDir(t)
	name := `it's $HOME "x"`
	if err := (kitty.TermKeyWriter{}).Write(context.Background(), []revier.TermBinding{
		{Chord: "ctrl+shift+d", Args: []string{"agent", "new", name}},
	}); err != nil {
		t.Fatal(err)
	}
	line := strings.Split(read(t, filepath.Join(dir, "revier.conf")), "\n")[1]
	words := posixWords(t, line)
	if len(words) != 11 || words[7] != "-c" || words[9] != "sh" || words[10] != "@active-kitty-window-id" {
		t.Fatalf("kitty reads %q", words)
	}
	script := posixWords(t, words[8])
	want := []string{"revier", "agent", "new", name, "--panel", "$1", "--dir", ".", "||", "kitten", "@", "launch", "--type=tab", "--cwd=current"}
	if !slices.Equal(script, want) {
		t.Errorf("sh reads %q\nwant %q", script, want)
	}
	if got := state(t).Bindings; len(got) != 1 || got[0].Args[2] != name {
		t.Errorf("read back %+v, want the name whole", got)
	}
}

// posixWords splits a line as sh does, with its quotes: what kitty does to a
// map's arguments, and sh to the script. "$1" keeps its dollar sign: sh
// expands it when the script runs, which this does not.
func posixWords(t *testing.T, s string) []string {
	t.Helper()
	var out []string
	var w strings.Builder
	started := false
	for i := 0; i < len(s); i++ {
		switch c := s[i]; c {
		case ' ':
			if started {
				out, started = append(out, w.String()), false
				w.Reset()
			}
			continue
		case '\'':
			j := strings.IndexByte(s[i+1:], '\'')
			if j < 0 {
				t.Fatalf("unclosed ' in %s", s)
			}
			w.WriteString(s[i+1 : i+1+j])
			i += j + 1
		case '"':
			for i++; i < len(s) && s[i] != '"'; i++ {
				if s[i] == '$' && i+1 < len(s) && s[i+1] != '1' {
					t.Fatalf("a $ sh would expand inside double quotes: %s", s)
				}
				if s[i] == '\\' {
					i++
				}
				w.WriteByte(s[i])
			}
			if i >= len(s) {
				t.Fatalf(`unclosed " in %s`, s)
			}
		case '\\':
			i++
			w.WriteByte(s[i])
		case '$', '`', ';', '&', '(', ')', '<', '>':
			t.Fatalf("unquoted %c in %s", c, s)
		default:
			w.WriteByte(c)
		}
		started = true
	}
	if started {
		out = append(out, w.String())
	}
	return out
}

// Read gives back what Write wrote, the chord in a spelling the core parses
// to the one it gave: kitty's key names in the file, revier's after.
func TestBindingsReadBackAsWritten(t *testing.T) {
	dir := kittyDir(t)
	want := append(slices.Clone(bindings), revier.TermBinding{Chord: "ctrl+shift+pgdown", Args: []string{"agent", "new", "x"}},
		revier.TermBinding{Chord: "ctrl+alt+esc", Args: []string{"agent", "new", "y"}},
		revier.TermBinding{Chord: "ctrl+shift+[", Args: []string{"agent", "new", "z"}})
	if err := (kitty.TermKeyWriter{}).Write(context.Background(), want); err != nil {
		t.Fatal(err)
	}
	text := read(t, filepath.Join(dir, "revier.conf"))
	for _, k := range []string{"map ctrl+shift+page_down ", "map ctrl+alt+escape ", "map ctrl+shift+left_bracket "} {
		if !strings.Contains(text, k) {
			t.Errorf("revier.conf has no %q:\n%s", k, text)
		}
	}
	got := state(t).Bindings
	if len(got) != len(want) {
		t.Fatalf("read %d bindings, want %d: %+v", len(got), len(want), got)
	}
	for i := range want {
		ch, err := core.ParseChord(got[i].Chord)
		if err != nil || string(ch) != want[i].Chord || !slices.Equal(got[i].Args, want[i].Args) {
			t.Errorf("binding %d = %+v (%v), want %+v", i, got[i], err, want[i])
		}
	}
}

// The user's kitty directory is a folded stow link into a dotfiles
// repository: the files land in the repository, and the link stays.
func TestAFoldedStowDirectoryIsWrittenThrough(t *testing.T) {
	root := t.TempDir()
	repo := filepath.Join(root, "setup", "dotfiles", "kitty", ".config", "kitty")
	write(t, filepath.Join(repo, "kitty.conf"), "map ctrl+c copy_or_interrupt\n", 0o644)
	dir := filepath.Join(root, "config", "kitty")
	if err := os.MkdirAll(filepath.Dir(dir), 0o755); err != nil {
		t.Fatal(err)
	}
	link(t, "../setup/dotfiles/kitty/.config/kitty", dir)
	t.Setenv("KITTY_CONFIG_DIRECTORY", dir)

	install(t)
	if !isLink(t, dir) {
		t.Error("the kitty directory is no longer a link")
	}
	if got := read(t, filepath.Join(repo, "kitty.conf")); got != marker+"map ctrl+c copy_or_interrupt\n" {
		t.Errorf("kitty.conf in the repository =\n%s", got)
	}
	if _, err := os.Stat(filepath.Join(repo, "revier.conf")); err != nil {
		t.Errorf("revier.conf is not in the repository: %v", err)
	}
	uninstall(t)
	if _, err := os.Lstat(filepath.Join(repo, "revier.conf")); !os.IsNotExist(err) {
		t.Errorf("revier.conf is still in the repository: %v", err)
	}
	if got := read(t, filepath.Join(repo, "kitty.conf")); got != "map ctrl+c copy_or_interrupt\n" {
		t.Errorf("kitty.conf after uninstall =\n%s", got)
	}
}

// kitty.conf may be a link of its own, through a chain: the file at the end
// is written, every link stays, and the file keeps its mode.
func TestAKittyConfLinkChainIsWrittenThroughAndKeepsItsMode(t *testing.T) {
	dir := kittyDir(t)
	repo := t.TempDir()
	write(t, filepath.Join(repo, "real.conf"), "font_size 11\n", 0o600)
	link(t, filepath.Join(repo, "real.conf"), filepath.Join(repo, "middle.conf"))
	link(t, filepath.Join(repo, "middle.conf"), filepath.Join(dir, "kitty.conf"))

	install(t)
	for _, p := range []string{filepath.Join(dir, "kitty.conf"), filepath.Join(repo, "middle.conf")} {
		if !isLink(t, p) {
			t.Errorf("%s is no longer a link", p)
		}
	}
	if got := read(t, filepath.Join(repo, "real.conf")); got != marker+"font_size 11\n" {
		t.Errorf("real.conf =\n%s", got)
	}
	info, err := os.Stat(filepath.Join(repo, "real.conf"))
	if err != nil || info.Mode().Perm() != 0o600 {
		t.Errorf("mode = %v, %v; want 0600 kept", info.Mode().Perm(), err)
	}
	if s := state(t); s.Include != 2 || !s.IncludeOwned {
		t.Errorf("include at %d, owned %v; want revier's at line 2", s.Include, s.IncludeOwned)
	}
}

// A link that points at nothing is refused before anything is written, and
// stays as it was: writing beside it would replace it with a file. Read
// names it, and neither Write nor Remove touches the other file.
func TestADanglingLinkIsRefused(t *testing.T) {
	for _, name := range []string{"kitty.conf", "revier.conf"} {
		t.Run(name, func(t *testing.T) {
			dir := kittyDir(t)
			path := filepath.Join(dir, name)
			link(t, filepath.Join(t.TempDir(), "gone"), path)
			s := state(t)
			if got := map[string]string{"kitty.conf": s.ConfigDangling, "revier.conf": s.FileDangling}[name]; got != path {
				t.Errorf("Read names %q as a link to nothing, want %q", got, path)
			}
			for op, run := range map[string]func(context.Context) error{
				"Write":  func(ctx context.Context) error { return (kitty.TermKeyWriter{}).Write(ctx, bindings) },
				"Remove": (kitty.TermKeyWriter{}).Remove,
			} {
				err := run(context.Background())
				if err == nil || err.Error() != path+" is a link to nothing" {
					t.Errorf("%s: err = %v, want %s is a link to nothing", op, err, path)
				}
			}
			if !isLink(t, path) {
				t.Errorf("%s was replaced", name)
			}
			if entries, _ := os.ReadDir(dir); len(entries) != 1 {
				t.Errorf("the directory holds %d entries, want the link alone: a refused run wrote", len(entries))
			}
		})
	}
}

// A kitty directory that is itself a link to nothing is named as one, for
// both files, and nothing is made in its place.
func TestADanglingConfigDirectoryIsRefused(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "kitty")
	link(t, filepath.Join(root, "gone"), dir)
	t.Setenv("KITTY_CONFIG_DIRECTORY", dir)
	if s := state(t); s.FileDangling != dir || s.ConfigDangling != dir {
		t.Errorf("Read: file %q, config %q; want both %q", s.FileDangling, s.ConfigDangling, dir)
	}
	err := (kitty.TermKeyWriter{}).Write(context.Background(), bindings)
	if err == nil || err.Error() != dir+" is a link to nothing" {
		t.Errorf("err = %v, want %s is a link to nothing", err, dir)
	}
	if !isLink(t, dir) {
		t.Error("the directory link was replaced")
	}
}

