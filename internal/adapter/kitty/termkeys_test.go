// An include the user wrote counts: install adds no second one, and
// uninstall leaves it.
func TestAUsersIncludeIsKept(t *testing.T) {
	for _, line := range []string{"include revier.conf", "include ./revier.conf", "globinclude *.conf"} {
		t.Run(line, func(t *testing.T) {
			dir := kittyDir(t)
			text := "font_size 11\n" + line + "\n"
			write(t, filepath.Join(dir, "kitty.conf"), text, 0o644)
			install(t)
			if got := read(t, filepath.Join(dir, "kitty.conf")); got != text {
				t.Errorf("kitty.conf changed:\n%s", got)
			}
			if s := state(t); s.Include != 2 || s.IncludeOwned {
				t.Errorf("include at %d, owned %v; want the user's at line 2", s.Include, s.IncludeOwned)
			}
			uninstall(t)
			if got := read(t, filepath.Join(dir, "kitty.conf")); got != text {
				t.Errorf("uninstall changed kitty.conf:\n%s", got)
			}
		})
	}
}

// A second install writes neither file: both are what it would write.
func TestASecondInstallWritesNothing(t *testing.T) {
	dir := kittyDir(t)
	write(t, filepath.Join(dir, "kitty.conf"), "font_size 11\n", 0o644)
	install(t)
	before := map[string]os.FileInfo{}
	for _, name := range []string{"kitty.conf", "revier.conf"} {
		info, err := os.Stat(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		before[name] = info
	}
	install(t)
	for name, info := range before {
		now, err := os.Stat(filepath.Join(dir, name))
		if err != nil || !os.SameFile(info, now) {
			t.Errorf("%s was written again", name)
		}
	}
	if got := read(t, filepath.Join(dir, "kitty.conf")); strings.Count(got, "include revier.conf") != 1 {
		t.Errorf("kitty.conf =\n%s", got)
	}
}

// Uninstall takes out revier's marked pair and nothing else: not a user's
// line that looks like it, not a lone marker.
func TestUninstallRemovesOnlyTheMarkedPair(t *testing.T) {
	dir := kittyDir(t)
	user := "# my keys\nmap ctrl+c copy_or_interrupt\n"
	write(t, filepath.Join(dir, "kitty.conf"), user, 0o644)
	install(t)
	uninstall(t)
	if got := read(t, filepath.Join(dir, "kitty.conf")); got != user {
		t.Errorf("kitty.conf =\n%s\nwant\n%s", got, user)
	}
	if _, err := os.Lstat(filepath.Join(dir, "revier.conf")); !os.IsNotExist(err) {
		t.Errorf("revier.conf is still there: %v", err)
	}
	uninstall(t) // nothing left: no error
}

// A kitty.conf that install created holds revier's pair alone, so uninstall
// removes it, through the folded directory link it is behind. A kitty.conf
// that is itself a link is emptied instead: removing the file would leave a
// link to nothing.
func TestUninstallRemovesAKittyConfItLeavesEmpty(t *testing.T) {
	root := t.TempDir()
	real := filepath.Join(root, "dotfiles")
	write(t, filepath.Join(real, "keep"), "", 0o644)
	dir := filepath.Join(root, "kitty")
	link(t, real, dir)
	t.Setenv("KITTY_CONFIG_DIRECTORY", dir)
	install(t)
	uninstall(t)
	if _, err := os.Stat(filepath.Join(real, "kitty.conf")); !os.IsNotExist(err) {
		t.Errorf("the empty kitty.conf is still there: %v", err)
	}
	if !isLink(t, dir) {
		t.Error("the directory link was replaced")
	}

	linked := kittyDir(t)
	file := filepath.Join(t.TempDir(), "kitty.conf")
	write(t, file, "", 0o644)
	link(t, file, filepath.Join(linked, "kitty.conf"))
	install(t)
	uninstall(t)
	if got := read(t, filepath.Join(linked, "kitty.conf")); got != "" || !isLink(t, filepath.Join(linked, "kitty.conf")) {
		t.Errorf("kitty.conf link: content %q, want an empty file behind the link", got)
	}
}

// The user's own layout: a theme include at the top, unconditional maps of
// revier's keys written by hand, and maps for windows that run tmux below.
// After install the include is first, every map is still where kitty reads
// it last, and Read reports each with its line and condition.
func TestTheUsersLayoutKeepsItsMapsBelowTheInclude(t *testing.T) {
	dir := kittyDir(t)
	conf := strings.Join([]string{
		"# kitty",
		"include current-theme.conf",
		"kitty_mod ctrl+alt",
		`map ctrl+shift+t launch --type=background --copy-env sh -lc 'revier shell new --panel "$1"' sh @active-kitty-window-id`,
		"map --when-focus-on var:in_tmux ctrl+shift+t     send_text all \\x02c",
		"map --when-focus-on=var:in_tmux ctrl+shift+z     send_text all \\x02A",
		"map kitty_mod+d new_window",
		"map --mode resize ctrl+shift+t noop",
		"map ctrl+x>ctrl+shift+t noop",
		"",
	}, "\n")
	write(t, filepath.Join(dir, "kitty.conf"), conf, 0o644)
	install(t)
	if got := read(t, filepath.Join(dir, "kitty.conf")); got != marker+conf {
		t.Errorf("kitty.conf =\n%s", got)
	}
	s := state(t)
	if s.Include != 2 || !s.IncludeOwned {
		t.Errorf("include at %d, owned %v; want revier's at line 2, not the theme's", s.Include, s.IncludeOwned)
	}
	want := []revier.TermMap{
		{Chord: "ctrl+shift+t", Line: 6},
		{Chord: "ctrl+shift+t", Line: 7, Condition: "when var:in_tmux"},
		{Chord: "ctrl+shift+z", Line: 8, Condition: "when var:in_tmux"},
		{Chord: "ctrl+alt+d", Line: 9},
	}
	if !reflect.DeepEqual(s.Maps, want) {
		t.Errorf("maps =\n%+v\nwant\n%+v", s.Maps, want)
	}
}

// kitty's own lookup: its variable, then XDG_CONFIG_HOME where that holds a
// kitty.conf, then ~/.config.
func TestTheConfigDirectoryIsFoundAsKittyFindsIt(t *testing.T) {
	home, xdg := t.TempDir(), t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("XDG_CONFIG_HOME", xdg)
	t.Setenv("KITTY_CONFIG_DIRECTORY", "/somewhere")
	check := func(want string) {
		t.Helper()
		if got, err := kitty.ConfigDir(); err != nil || got != want {
			t.Errorf("ConfigDir = %q, %v; want %q", got, err, want)
		}
	}
	check("/somewhere")
	t.Setenv("KITTY_CONFIG_DIRECTORY", "")
	check(filepath.Join(home, ".config", "kitty"))
	write(t, filepath.Join(xdg, "kitty", "kitty.conf"), "", 0o644)
	check(filepath.Join(xdg, "kitty"))
}
